#include "libft.h"

int	ft_atoi(const char *ptr)
{
	int	i;

	i = 0;
	


	while ((ptr[i] >= 9 && ptr[i] <= 13) || ptr[i] == 32)
	{
		i++;
	}

	while (ptr[i] >= '0' && ptr[i] <= '9')
	{
		
		i++;
	}
	return (0);
}
